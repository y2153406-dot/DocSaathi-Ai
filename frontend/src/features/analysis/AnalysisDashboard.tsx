"use client";

import React, { useState } from "react";
import {
  FileText,
  Calendar,
  IndianRupee,
  GraduationCap,
  FolderCheck,
  AlertOctagon,
  AlertTriangle,
  Download,
  Share2,
  CheckCircle,
  Clock,
  Sparkles,
  ExternalLink,
  Info,
} from "lucide-react";
import { useLanguage } from "@/contexts/LanguageContext";
import { useAnalysis } from "@/contexts/AnalysisContext";
import { GlassCard } from "@/components/common/GlassCard";
import { Button } from "@/components/common/Button";
import { Badge } from "@/components/common/Badge";
import { SmartActionChecklist } from "../checklist/SmartActionChecklist";
import { AudioSummaryPlayer } from "../speech/AudioSummaryPlayer";
import { DocumentChat } from "../chat/DocumentChat";

export function AnalysisDashboard() {
  const { t, meta } = useLanguage();
  const { analysis } = useAnalysis();
  const [viewMode, setViewMode] = useState<"dual" | "native" | "english">("dual");

  if (!analysis) return null;

  // WhatsApp share generator
  const handleShareWhatsApp = () => {
    const text = [
      `🇮🇳 *DocSaathi AI Summary: ${analysis.title || analysis.documentType}*`,
      `📄 *Type:* ${analysis.documentType}`,
      "",
      `📝 *Summary:* ${analysis.simpleSummary}`,
      "",
      "🔑 *Key Points:*",
      ...analysis.keyPoints.slice(0, 3).map((p) => `• ${p}`),
      "",
      "📅 *Crucial Dates:*",
      ...analysis.importantDates.map((d) => `• ${d.event || d.title || "Date"}: ${d.date} (${d.daysLeft ? `${d.daysLeft} days left` : "Active"})`),
      "",
      "🚀 Simplified by DocSaathi AI — Understand Documents. Know What to Do Next.",
    ].join("\n");

    const url = `https://api.whatsapp.com/send?text=${encodeURIComponent(text)}`;
    window.open(url, "_blank");
  };

  // Download Markdown summary
  const handleDownloadMarkdown = () => {
    const mdContent = [
      `# ${analysis.title || analysis.documentType}`,
      `**Document Type:** ${analysis.documentType}`,
      `**Language:** ${analysis.language}`,
      `**Date of Analysis:** ${new Date().toLocaleDateString()}`,
      "",
      "## Simple Summary",
      analysis.simpleSummary,
      "",
      "## Key Points",
      ...analysis.keyPoints.map((p) => `- ${p}`),
      "",
      "## Crucial Dates & Deadlines",
      ...analysis.importantDates.map(
        (d) => `- **${d.title || d.event || "Date"}**: ${d.date} ${d.daysLeft ? `(${d.daysLeft} days left)` : ""}`
      ),
      "",
      "## Fees & Financial Overview",
      ...analysis.feesAndAmounts.map((f) => `- **${f.category || f.label || "Amount"}**: ${f.amount} (${f.details || ""})`),
      "",
      "## Eligibility & Prerequisites",
      ...analysis.eligibility.map((e) => `- **${e.criteria || e.criterion || "Criterion"}**: ${e.requirement || e.detail || e.status || ""}`),
      "",
      "## Required Documents",
      ...analysis.requiredDocuments.map(
        (rd) => `- [ ] **${rd.name}** (${rd.mandatory || rd.isMandatory ? "Mandatory" : "Optional"})`
      ),
      "",
      "## Smart Action Checklist",
      ...analysis.actionChecklist.map(
        (a, i) => `${i + 1}. [ ] **${a.task}** [${a.priority.toUpperCase()}]\n   ${a.description}`
      ),
      "",
      "## Caution Notes & Warnings",
      ...analysis.cautionNotes.map((w) => `> ⚠️ ${w}`),
      "",
      "---",
      "Generated by DocSaathi AI.",
    ].join("\n");

    const blob = new Blob([mdContent], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${(analysis.title || "DocSaathi_Summary").replace(/\s+/g, "_")}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="w-full max-w-5xl mx-auto space-y-8 py-6">
      {/* Top Banner & Title */}
      <GlassCard variant="elevated" className="p-6 sm:p-8 space-y-4 border border-theme-borderGlow">
        <div className="flex flex-wrap items-center justify-between gap-3 pb-4 border-b border-theme-border/60">
          <div className="flex items-center gap-2">
            <Badge variant="theme" size="md">
              {analysis.documentType}
            </Badge>
            <Badge variant="success" size="sm" className="gap-1">
              <Sparkles className="w-3 h-3 text-emerald-500" /> Real-Time Analysis
            </Badge>
          </div>

          <div className="flex items-center gap-2">
            <Button
              variant="outline"
              size="sm"
              onClick={handleDownloadMarkdown}
              className="text-xs"
            >
              <Download className="w-3.5 h-3.5 mr-1" />
              <span>{t.results.downloadMarkdown}</span>
            </Button>
            <Button
              variant="secondary"
              size="sm"
              onClick={handleShareWhatsApp}
              className="text-xs text-emerald-400 border-emerald-500/30 hover:bg-emerald-500/10"
            >
              <Share2 className="w-3.5 h-3.5 mr-1" />
              <span>{t.results.shareWhatsApp}</span>
            </Button>
          </div>
        </div>

        <div className="space-y-2">
          <h2 className="text-2xl sm:text-3xl font-extrabold text-theme-text font-display">
            {analysis.title || analysis.documentType}
          </h2>
          <div className="flex flex-wrap items-center gap-2 pt-1 text-xs text-theme-textMuted">
            {analysis.originalFilename && (
              <span className="flex items-center gap-1 bg-slate-100 text-slate-700 px-2.5 py-0.5 rounded-full font-medium">
                <FileText className="w-3 h-3 text-slate-500" />
                {analysis.originalFilename}
              </span>
            )}
            {analysis.fileHash && (
              <span className="flex items-center gap-1 bg-slate-100 text-slate-600 px-2 py-0.5 rounded-full font-mono text-[10px]" title={`Full SHA-256: ${analysis.fileHash}`}>
                SHA-256: {analysis.fileHash.slice(0, 12)}...
              </span>
            )}
            {analysis.modelUsed && (
              <span className="flex items-center gap-1 bg-emerald-50 text-emerald-700 border border-emerald-200 px-2 py-0.5 rounded-full text-[10px] font-semibold">
                <Sparkles className="w-3 h-3 text-emerald-600" />
                {analysis.modelUsed}
              </span>
            )}
            <span className="text-[11px] text-theme-textMuted">
              • {t.results.subtitle}
            </span>
          </div>
        </div>

        {/* Language View Switcher */}
        <div className="flex flex-wrap items-center justify-between gap-3 pt-2">
          <div className="flex items-center gap-1.5 p-1 rounded-xl bg-theme-surfaceGlass border border-theme-border">
            <button
              type="button"
              onClick={() => setViewMode("dual")}
              className={`text-xs px-3 py-1.5 rounded-lg font-medium transition-all ${
                viewMode === "dual"
                  ? "bg-theme-primary text-theme-textInverse font-bold shadow-xs"
                  : "text-theme-textMuted hover:text-theme-text"
              }`}
            >
              🇮🇳 + 🇬🇧 दोनों भाषाएं (Dual: {meta.nativeName} + English)
            </button>
            <button
              type="button"
              onClick={() => setViewMode("native")}
              className={`text-xs px-3 py-1.5 rounded-lg font-medium transition-all ${
                viewMode === "native"
                  ? "bg-theme-primary text-theme-textInverse font-bold shadow-xs"
                  : "text-theme-textMuted hover:text-theme-text"
              }`}
            >
              🇮🇳 केवल {meta.nativeName}
            </button>
            <button
              type="button"
              onClick={() => setViewMode("english")}
              className={`text-xs px-3 py-1.5 rounded-lg font-medium transition-all ${
                viewMode === "english"
                  ? "bg-theme-primary text-theme-textInverse font-bold shadow-xs"
                  : "text-theme-textMuted hover:text-theme-text"
              }`}
            >
              🇬🇧 English Only
            </button>
          </div>

          <div className="text-[11px] text-theme-textMuted font-medium flex items-center gap-1.5">
            <span>Audio Voice:</span>
            <span className="font-bold text-theme-primary bg-theme-primary/10 px-2 py-0.5 rounded-md">
              🔊 {meta.nativeName} ({meta.name})
            </span>
          </div>
        </div>

        {/* Section 2: Simple Summary (Dual or Single View) */}
        {viewMode === "dual" ? (
          <div className="space-y-3.5">
            {/* Native Language Summary */}
            <div className="p-4 sm:p-5 rounded-2xl bg-theme-surfaceGlass border border-theme-primary/30 space-y-2">
              <div className="flex items-center justify-between gap-2">
                <div className="flex items-center gap-2 text-xs font-bold uppercase tracking-wider text-theme-primary">
                  <Sparkles className="w-4 h-4" />
                  <span>{t.results.simpleSummary}</span>
                </div>
                <Badge variant="theme" size="sm">
                  🇮🇳 {meta.nativeName}
                </Badge>
              </div>
              <p className="text-sm sm:text-base text-theme-text leading-relaxed font-sans">
                {analysis.simpleSummary}
              </p>
            </div>

            {/* English Summary */}
            <div className="p-4 sm:p-5 rounded-2xl bg-white/80 border border-slate-200 space-y-2">
              <div className="flex items-center justify-between gap-2">
                <div className="flex items-center gap-2 text-xs font-bold uppercase tracking-wider text-slate-700">
                  <FileText className="w-4 h-4 text-slate-500" />
                  <span>English Translation</span>
                </div>
                <Badge variant="neutral" size="sm">
                  🇬🇧 English
                </Badge>
              </div>
              <p className="text-sm sm:text-base text-slate-800 leading-relaxed font-sans">
                {analysis.simpleSummaryEnglish || analysis.simpleSummary}
              </p>
            </div>
          </div>
        ) : viewMode === "native" ? (
          <div className="p-4 sm:p-5 rounded-2xl bg-theme-surfaceGlass border border-theme-primary/30 space-y-2">
            <div className="flex items-center justify-between gap-2">
              <div className="flex items-center gap-2 text-xs font-bold uppercase tracking-wider text-theme-primary">
                <Sparkles className="w-4 h-4" />
                <span>{t.results.simpleSummary}</span>
              </div>
              <Badge variant="theme" size="sm">
                🇮🇳 {meta.nativeName}
              </Badge>
            </div>
            <p className="text-sm sm:text-base text-theme-text leading-relaxed font-sans">
              {analysis.simpleSummary}
            </p>
          </div>
        ) : (
          <div className="p-4 sm:p-5 rounded-2xl bg-white/80 border border-slate-200 space-y-2">
            <div className="flex items-center justify-between gap-2">
              <div className="flex items-center gap-2 text-xs font-bold uppercase tracking-wider text-slate-700">
                <FileText className="w-4 h-4 text-slate-500" />
                <span>English Summary</span>
              </div>
              <Badge variant="neutral" size="sm">
                🇬🇧 English
              </Badge>
            </div>
            <p className="text-sm sm:text-base text-slate-800 leading-relaxed font-sans">
              {analysis.simpleSummaryEnglish || analysis.simpleSummary}
            </p>
          </div>
        )}

        {/* Section 10 Embedded Preview: Audio Voice Briefing */}
        <div className="pt-2">
          <AudioSummaryPlayer />
        </div>
      </GlassCard>

      {/* Grid: Key Points (Section 3) & Crucial Dates (Section 4) */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        
        {/* Section 3: Important Points */}
        <GlassCard variant="default" className="p-6 space-y-4">
          <div className="flex items-center justify-between pb-3 border-b border-theme-border/60">
            <div className="flex items-center gap-2 text-sm font-bold text-theme-text font-display">
              <CheckCircle className="w-4 h-4 text-theme-primary" />
              <span>{t.results.keyPoints}</span>
            </div>
            <Badge variant="theme" size="sm" className="text-[10px]">
              {viewMode === "dual" ? "Bilingual" : viewMode === "native" ? meta.nativeName : "English"}
            </Badge>
          </div>
          <ul className="space-y-3.5">
            {analysis.keyPoints.map((point, idx) => {
              const englishPoint = analysis.keyPointsEnglish?.[idx];
              return (
                <li key={idx} className="flex items-start gap-2.5 text-xs sm:text-sm text-theme-text leading-relaxed">
                  <span className="w-1.5 h-1.5 rounded-full bg-theme-primary mt-2 shrink-0" />
                  <div className="space-y-0.5">
                    {viewMode !== "english" && (
                      <div className="text-theme-text font-medium">{point}</div>
                    )}
                    {(viewMode === "dual" || viewMode === "english") && englishPoint && (
                      <div
                        className={`text-xs ${
                          viewMode === "dual"
                            ? "text-slate-500 font-sans italic"
                            : "text-theme-text font-medium"
                        }`}
                      >
                        {viewMode === "dual" ? `🇬🇧 ${englishPoint}` : englishPoint}
                      </div>
                    )}
                  </div>
                </li>
              );
            })}
          </ul>
        </GlassCard>

        {/* Section 4: Important Dates & Deadlines */}
        <GlassCard variant="default" className="p-6 space-y-4">
          <div className="flex items-center justify-between pb-3 border-b border-theme-border/60">
            <div className="flex items-center gap-2 text-sm font-bold text-theme-text font-display">
              <Calendar className="w-4 h-4 text-amber-400" />
              <span>{t.results.importantDates}</span>
            </div>
            <span className="text-[11px] font-mono text-theme-textMuted">Official Cutoffs</span>
          </div>
          <div className="space-y-3">
            {analysis.importantDates.map((d, idx) => (
              <div
                key={d.id || `date-${idx}`}
                className="p-3 rounded-xl bg-theme-surfaceGlass border border-theme-border space-y-1"
              >
                <div className="flex items-center justify-between gap-2">
                  <span className="text-xs font-bold text-theme-text">{d.title || d.event || "Important Date"}</span>
                  {d.daysLeft !== undefined && (
                    <Badge variant={d.urgency === "urgent" ? "urgent" : "warning"} size="sm">
                      {d.daysLeft} {t.results.daysLeft}
                    </Badge>
                  )}
                </div>
                <div className="text-xs font-mono text-theme-primary font-semibold">
                  {d.date}
                </div>
                {d.note && (
                  <div className="text-[11px] text-theme-textMuted">{d.note}</div>
                )}
              </div>
            ))}
          </div>
        </GlassCard>
      </div>

      {/* Grid: Fees & Amounts (Section 5) & Eligibility (Section 6) */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        
        {/* Section 5: Fees & Financial Overview */}
        <GlassCard variant="default" className="p-6 space-y-4">
          <div className="flex items-center gap-2 text-sm font-bold text-theme-text font-display pb-3 border-b border-theme-border/60">
            <IndianRupee className="w-4 h-4 text-emerald-400" />
            <span>{t.results.feesAndAmounts}</span>
          </div>
          <div className="space-y-3">
            {analysis.feesAndAmounts.map((fee, idx) => (
              <div
                key={idx}
                className="p-3.5 rounded-xl bg-theme-surfaceGlass border border-theme-border space-y-1"
              >
                <div className="flex items-center justify-between gap-2">
                  <span className="text-xs font-medium text-theme-textMuted">{fee.category}</span>
                  <span className="text-sm font-bold font-mono text-emerald-400">{fee.amount}</span>
                </div>
                {fee.details && (
                  <p className="text-[11px] text-theme-textMuted leading-relaxed">{fee.details}</p>
                )}
              </div>
            ))}
          </div>
        </GlassCard>

        {/* Section 6: Eligibility & Prerequisites */}
        <GlassCard variant="default" className="p-6 space-y-4">
          <div className="flex items-center gap-2 text-sm font-bold text-theme-text font-display pb-3 border-b border-theme-border/60">
            <GraduationCap className="w-4 h-4 text-theme-accent" />
            <span>{t.results.eligibility}</span>
          </div>
          <div className="space-y-3">
            {analysis.eligibility.map((el, idx) => (
              <div
                key={idx}
                className="p-3.5 rounded-xl bg-theme-surfaceGlass border border-theme-border space-y-1"
              >
                <div className="flex items-center justify-between gap-2">
                  <span className="text-xs font-bold text-theme-text">{el.criteria}</span>
                  {el.status && (
                    <Badge variant={el.status === "mandatory" ? "primary" : "neutral"} size="sm" className="text-[10px]">
                      {el.status}
                    </Badge>
                  )}
                </div>
                <p className="text-xs text-theme-textMuted leading-relaxed">{el.requirement}</p>
              </div>
            ))}
          </div>
        </GlassCard>
      </div>

      {/* Section 7: Required Documents */}
      <GlassCard variant="default" className="p-6 space-y-4">
        <div className="flex items-center gap-2 text-sm font-bold text-theme-text font-display pb-3 border-b border-theme-border/60">
          <FolderCheck className="w-4 h-4 text-blue-400" />
          <span>{t.results.requiredDocs}</span>
        </div>
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
          {analysis.requiredDocuments.map((doc, idx) => (
            <div
              key={doc.id || `req-doc-${idx}`}
              className="p-3.5 rounded-xl bg-theme-surfaceGlass border border-theme-border space-y-1"
            >
              <div className="flex items-center justify-between gap-2">
                <span className="text-xs font-bold text-theme-text">{doc.name}</span>
                <Badge variant={doc.mandatory || doc.isMandatory ? "urgent" : "neutral"} size="sm" className="text-[10px]">
                  {doc.mandatory || doc.isMandatory ? t.results.mandatory : t.results.optional}
                </Badge>
              </div>
              {(doc.details || doc.notes) && (
                <p className="text-[11px] text-theme-textMuted">{doc.details || doc.notes}</p>
              )}
            </div>
          ))}
        </div>
      </GlassCard>

      {/* Grid: Missing Information (Section 8) & Important Warnings (Section 9) */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        
        {/* Section 8: Missing Information */}
        <GlassCard variant="default" className="p-6 space-y-4">
          <div className="flex items-center gap-2 text-sm font-bold text-theme-text font-display pb-3 border-b border-theme-border/60">
            <Info className="w-4 h-4 text-cyan-400" />
            <span>{t.results.missingInfo}</span>
          </div>
          {analysis.missingInformation.length > 0 ? (
            <ul className="space-y-2.5">
              {analysis.missingInformation.map((item, idx) => (
                <li key={idx} className="flex items-start gap-2 text-xs text-theme-textMuted leading-relaxed">
                  <span className="w-1.5 h-1.5 rounded-full bg-cyan-400 mt-1.5 shrink-0" />
                  <span>{item}</span>
                </li>
              ))}
            </ul>
          ) : (
            <p className="text-xs text-theme-textMuted">No material information was omitted in this notice.</p>
          )}
        </GlassCard>

        {/* Section 9: Important Warnings & Caution Notes */}
        <GlassCard variant="default" className="p-6 space-y-4 border border-amber-500/20">
          <div className="flex items-center gap-2 text-sm font-bold text-amber-300 font-display pb-3 border-b border-amber-500/20">
            <AlertOctagon className="w-4 h-4 text-amber-400" />
            <span>{t.results.cautionNotes}</span>
          </div>
          <ul className="space-y-2.5">
            {analysis.cautionNotes.map((note, idx) => (
              <li key={idx} className="flex items-start gap-2 text-xs text-amber-200/90 leading-relaxed bg-amber-500/5 p-2 rounded-xl border border-amber-500/15">
                <AlertTriangle className="w-3.5 h-3.5 text-amber-400 shrink-0 mt-0.5" />
                <span>{note}</span>
              </li>
            ))}
          </ul>
        </GlassCard>
      </div>

      {/* Section 10: Smart Action Checklist (Primary Feature) */}
      <div className="pt-2">
        <SmartActionChecklist />
      </div>

      {/* Section 11: Ask Your Document Q&A */}
      <div className="pt-2">
        <DocumentChat />
      </div>
    </div>
  );
}
