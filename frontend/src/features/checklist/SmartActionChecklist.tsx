"use client";

import React, { useState } from "react";
import confetti from "canvas-confetti";
import {
  CheckSquare,
  Square,
  Clock,
  RotateCcw,
  Copy,
  Check,
  ListTodo,
  Sparkles,
  BookOpen,
  Plus,
  Trash2,
  Tag,
  Calendar,
} from "lucide-react";
import { useLanguage } from "@/contexts/LanguageContext";
import { useAnalysis } from "@/contexts/AnalysisContext";
import { GlassCard } from "@/components/common/GlassCard";
import { Button } from "@/components/common/Button";
import { Badge } from "@/components/common/Badge";
import { copyToClipboard } from "@/lib/utils";
import { ActionChecklistItem } from "@/types/api";

interface CustomTask extends ActionChecklistItem {
  isPersonal?: boolean;
}

export function SmartActionChecklist() {
  const { t } = useLanguage();
  const {
    analysis,
    completedTasks,
    toggleTask,
    resetChecklist,
  } = useAnalysis();

  const [copied, setCopied] = useState(false);
  const [personalTasks, setPersonalTasks] = useState<CustomTask[]>([]);
  const [isAddingTask, setIsAddingTask] = useState(false);
  const [newTaskTitle, setNewTaskTitle] = useState("");
  const [newTaskDesc, setNewTaskDesc] = useState("");
  const [newTaskDeadline, setNewTaskDeadline] = useState("");

  if (!analysis) return null;

  const aiTasks: CustomTask[] = (analysis.actionChecklist || []).map((task) => ({
    ...task,
    isPersonal: false,
  }));

  const allTasks: CustomTask[] = [...aiTasks, ...personalTasks];
  const totalTasksCount = allTasks.length;
  const completedTasksCount = allTasks.filter((t) => !!completedTasks[t.id]).length;
  const checklistProgress =
    totalTasksCount > 0
      ? Math.round((completedTasksCount / totalTasksCount) * 100)
      : 0;

  const handleToggle = (taskId: string) => {
    toggleTask(taskId);
    const willBeCompleted = !completedTasks[taskId];
    const newCount = willBeCompleted
      ? completedTasksCount + 1
      : completedTasksCount - 1;

    if (newCount === totalTasksCount && totalTasksCount > 0) {
      try {
        confetti({
          particleCount: 80,
          spread: 70,
          origin: { y: 0.6 },
          colors: ["#2B44B4", "#D97706", "#059669", "#DC2626"],
        });
      } catch {
        // Ignore in testing environments
      }
    }
  };

  const handleAddPersonalTask = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newTaskTitle.trim()) return;

    const task: CustomTask = {
      id: `personal-${Date.now()}`,
      task: newTaskTitle.trim(),
      description: newTaskDesc.trim() || "Candidate personal action item",
      deadline: newTaskDeadline.trim() || null,
      priority: "medium",
      category: "Personal Task",
      sourceText: undefined,
      isPersonal: true,
    };

    setPersonalTasks([...personalTasks, task]);
    setNewTaskTitle("");
    setNewTaskDesc("");
    setNewTaskDeadline("");
    setIsAddingTask(false);
  };

  const handleDeletePersonalTask = (taskId: string, e: React.MouseEvent) => {
    e.stopPropagation();
    setPersonalTasks(personalTasks.filter((t) => t.id !== taskId));
  };

  const handleCopyChecklist = async () => {
    if (!allTasks.length) return;
    const textLines = [
      `📋 DocSaathi AI Smart Action Checklist: ${analysis.title || analysis.documentType}`,
      `Progress: ${completedTasksCount}/${totalTasksCount} tasks completed (${checklistProgress}%)`,
      "",
      ...allTasks.map((task, idx) => {
        const isDone = completedTasks[task.id] ? "✅ [DONE]" : "⬜ [PENDING]";
        const deadline = task.deadline ? ` (Deadline: ${task.deadline})` : "";
        const tag = task.isPersonal ? "[PERSONAL]" : "[AI EXTRACTED]";
        const priority = `[${task.priority.toUpperCase()}]`;
        return `${idx + 1}. ${isDone} ${tag} ${priority} ${task.task}${deadline}\n   ${task.description}`;
      }),
      "",
      "Generated by DocSaathi AI — Understand Documents. Know What to Do Next.",
    ].join("\n");

    const success = await copyToClipboard(textLines);
    if (success) {
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    }
  };

  if (allTasks.length === 0) {
    return (
      <GlassCard variant="default" className="p-8 text-center space-y-3">
        <ListTodo className="w-12 h-12 text-theme-textMuted mx-auto opacity-50" />
        <h4 className="text-base font-bold text-theme-text font-display">
          No specific action items found in this document.
        </h4>
        <p className="text-xs text-theme-textMuted max-w-md mx-auto">
          This document is informational. You can also add your own personal checklist items below.
        </p>
        <div className="pt-2">
          <Button
            variant="secondary"
            size="sm"
            onClick={() => setIsAddingTask(true)}
            className="gap-1"
          >
            <Plus className="w-4 h-4" />
            <span>Add Personal Action Item</span>
          </Button>
        </div>
      </GlassCard>
    );
  }

  return (
    <GlassCard variant="elevated" className="p-6 sm:p-8 space-y-6">
      {/* Header & Controls */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-theme-border/60">
        <div className="space-y-1">
          <div className="flex items-center gap-2">
            <span className="p-1.5 rounded-xl bg-emerald-50 text-emerald-700 border border-emerald-200">
              <CheckSquare className="w-5 h-5" />
            </span>
            <h3 className="text-xl font-bold text-theme-text font-display">
              {t.checklist.heading}
            </h3>
          </div>
          <p className="text-xs text-theme-textMuted">
            {t.checklist.subheading}
          </p>
        </div>

        {/* Buttons */}
        <div className="flex flex-wrap items-center gap-2">
          <Button
            variant="secondary"
            size="sm"
            onClick={() => setIsAddingTask(!isAddingTask)}
            className="text-xs gap-1"
          >
            <Plus className="w-3.5 h-3.5" />
            <span>Add Personal Task</span>
          </Button>

          <Button
            variant="outline"
            size="sm"
            onClick={handleCopyChecklist}
            className="text-xs"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-600 mr-1" />
                <span>{t.checklist.copiedSuccess}</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5 mr-1" />
                <span>{t.checklist.copy}</span>
              </>
            )}
          </Button>

          <Button
            variant="ghost"
            size="sm"
            onClick={resetChecklist}
            className="text-xs text-theme-textMuted hover:text-theme-text"
          >
            <RotateCcw className="w-3.5 h-3.5 mr-1" />
            <span>{t.checklist.reset}</span>
          </Button>
        </div>
      </div>

      {/* Optional Form to Add Personal Task */}
      {isAddingTask && (
        <form
          onSubmit={handleAddPersonalTask}
          className="p-4 rounded-2xl bg-slate-50 border border-slate-200 space-y-3 transition-all"
        >
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold text-slate-800 flex items-center gap-1.5">
              <Plus className="w-3.5 h-3.5 text-theme-primary" />
              <span>Add Your Own Task</span>
            </span>
            <button
              type="button"
              onClick={() => setIsAddingTask(false)}
              className="text-xs text-slate-400 hover:text-slate-600"
            >
              Cancel
            </button>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-3 gap-2">
            <input
              type="text"
              value={newTaskTitle}
              onChange={(e) => setNewTaskTitle(e.target.value)}
              placeholder="Task title (e.g. Visit bank branch)..."
              className="sm:col-span-2 px-3 py-2 rounded-xl border border-slate-200 text-xs bg-white text-slate-900 focus:outline-none focus:ring-2 focus:ring-theme-primary"
              required
            />
            <input
              type="text"
              value={newTaskDeadline}
              onChange={(e) => setNewTaskDeadline(e.target.value)}
              placeholder="Deadline (optional)..."
              className="px-3 py-2 rounded-xl border border-slate-200 text-xs bg-white text-slate-900 focus:outline-none focus:ring-2 focus:ring-theme-primary"
            />
          </div>

          <div className="flex items-center gap-2">
            <input
              type="text"
              value={newTaskDesc}
              onChange={(e) => setNewTaskDesc(e.target.value)}
              placeholder="Details or notes (optional)..."
              className="flex-1 px-3 py-2 rounded-xl border border-slate-200 text-xs bg-white text-slate-900 focus:outline-none focus:ring-2 focus:ring-theme-primary"
            />
            <Button type="submit" variant="primary" size="sm" className="shrink-0 text-xs font-bold">
              Save Task
            </Button>
          </div>
        </form>
      )}

      {/* Progress Bar & Counters */}
      <div className="p-4 rounded-2xl bg-white border border-theme-border space-y-2.5 shadow-xs">
        <div className="flex items-center justify-between text-xs font-semibold">
          <span className="text-theme-text flex items-center gap-2">
            <span>{t.checklist.progress}:</span>
            <strong className="text-emerald-700 text-sm">{checklistProgress}%</strong>
          </span>
          <span className="text-theme-textMuted font-medium">
            {completedTasksCount} {t.checklist.completed} • {totalTasksCount - completedTasksCount} {t.checklist.pending}
          </span>
        </div>

        <div className="w-full bg-slate-100 rounded-full h-2.5 overflow-hidden border border-slate-200/60">
          <div
            className="bg-gradient-to-r from-emerald-600 via-teal-500 to-emerald-500 h-full rounded-full transition-all duration-500 ease-out"
            style={{ width: `${checklistProgress}%` }}
          />
        </div>

        {checklistProgress === 100 && (
          <div className="pt-1 flex items-center gap-2 text-xs font-semibold text-emerald-700">
            <Sparkles className="w-4 h-4" />
            <span>{t.checklist.allTasksCompleted}</span>
          </div>
        )}
      </div>

      {/* Tasks List */}
      <div className="space-y-3">
        {allTasks.map((task, index) => {
          const isDone = !!completedTasks[task.id];

          return (
            <div
              key={task.id}
              onClick={() => handleToggle(task.id)}
              className={`p-4 sm:p-5 rounded-2xl border transition-all duration-200 cursor-pointer select-none text-left ${
                isDone
                  ? "bg-emerald-50/50 border-emerald-300 opacity-90"
                  : "bg-white border-theme-border hover:border-theme-borderGlow hover:shadow-xs"
              }`}
            >
              <div className="flex items-start gap-3.5">
                {/* Checkbox Icon */}
                <button
                  type="button"
                  className={`mt-0.5 p-1 rounded-lg transition-colors ${
                    isDone
                      ? "text-emerald-700 bg-emerald-100"
                      : "text-slate-400 hover:text-slate-600"
                  }`}
                  aria-label={isDone ? "Mark incomplete" : "Mark complete"}
                >
                  {isDone ? (
                    <CheckSquare className="w-5 h-5 stroke-[2.5]" />
                  ) : (
                    <Square className="w-5 h-5" />
                  )}
                </button>

                {/* Content */}
                <div className="space-y-1.5 flex-1 min-w-0">
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <div className="space-y-0.5">
                      <span
                        className={`text-sm sm:text-base font-bold font-display ${
                          isDone ? "line-through text-slate-400" : "text-slate-900"
                        }`}
                      >
                        {index + 1}. {task.task}
                      </span>
                      {task.taskEnglish && task.taskEnglish !== task.task && (
                        <div className="text-xs text-slate-500 font-sans">
                          🇬🇧 {task.taskEnglish}
                        </div>
                      )}
                    </div>

                    <div className="flex items-center gap-2 shrink-0">
                      {/* Badge: AI Extracted vs Personal Task */}
                      {task.isPersonal ? (
                        <span className="text-[10px] uppercase font-bold px-2 py-0.5 rounded-full bg-indigo-50 text-indigo-700 border border-indigo-200">
                          Personal Task
                        </span>
                      ) : (
                        <span className="text-[10px] uppercase font-bold px-2 py-0.5 rounded-full bg-slate-100 text-slate-700 border border-slate-200">
                          AI Extracted
                        </span>
                      )}

                      <Badge
                        variant={
                          task.priority === "high"
                            ? "urgent"
                            : task.priority === "medium"
                            ? "warning"
                            : "neutral"
                        }
                        size="sm"
                        className="text-[10px]"
                      >
                        {task.priority === "high"
                          ? t.checklist.priorityHigh
                          : task.priority === "medium"
                          ? t.checklist.priorityMedium
                          : t.checklist.priorityLow}
                      </Badge>

                      {task.isPersonal && (
                        <button
                          type="button"
                          onClick={(e) => handleDeletePersonalTask(task.id, e)}
                          title="Delete personal task"
                          className="p-1 rounded text-slate-400 hover:text-red-600 hover:bg-red-50 transition-colors"
                        >
                          <Trash2 className="w-3.5 h-3.5" />
                        </button>
                      )}
                    </div>
                  </div>

                  <p
                    className={`text-xs leading-relaxed ${
                      isDone ? "line-through text-slate-400" : "text-slate-600"
                    }`}
                  >
                    {task.description}
                  </p>
                  {task.descriptionEnglish && task.descriptionEnglish !== task.description && (
                    <p className={`text-[11px] leading-relaxed italic ${isDone ? "text-slate-400" : "text-slate-500"}`}>
                      🇬🇧 {task.descriptionEnglish}
                    </p>
                  )}

                  {/* Deadline & Source evidence */}
                  <div className="pt-2 flex flex-wrap items-center justify-between gap-2 text-[11px] text-slate-500 border-t border-slate-100">
                    <div className="flex items-center gap-1.5">
                      <Clock className="w-3.5 h-3.5 text-amber-600" />
                      <span>
                        {t.checklist.deadline}:{" "}
                        <strong className="text-slate-800">
                          {task.deadline || t.checklist.noDeadline}
                        </strong>
                      </span>
                    </div>

                    {task.sourceText && (
                      <div className="flex items-center gap-1.5 text-theme-primary italic truncate max-w-sm">
                        <BookOpen className="w-3 h-3 shrink-0" />
                        <span className="truncate">Source: &quot;{task.sourceText}&quot;</span>
                      </div>
                    )}
                  </div>
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </GlassCard>
  );
}
