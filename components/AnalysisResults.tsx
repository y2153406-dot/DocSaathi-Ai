"use client";

import React, { useState } from "react";
import { DocumentAnalysis, UILanguage } from "@/types";
import { uiTranslations } from "@/data/translations";
import { AudioPlayer } from "@/components/AudioPlayer";
import { DocumentQnA } from "@/components/DocumentQnA";
import confetti from "canvas-confetti";
import {
  FileText,
  Calendar,
  UserCheck,
  CreditCard,
  FolderCheck,
  CheckSquare,
  Sparkles,
  ExternalLink,
  Share2,
  Download,
  AlertTriangle,
  Clock,
  Printer,
  ShieldAlert,
  ChevronRight,
  Info,
  CheckCircle2,
  RotateCcw
} from "lucide-react";

interface AnalysisResultsProps {
  analysis: DocumentAnalysis;
  uiLang: UILanguage;
  onReset: () => void;
  apiKey?: string;
}

export const AnalysisResults: React.FC<AnalysisResultsProps> = ({
  analysis,
  uiLang,
  onReset,
  apiKey,
}) => {
  const t = uiTranslations[uiLang].results;

  // Interactive state for documents held by user
  const [checkedDocs, setCheckedDocs] = useState<Record<string, boolean>>({});
  // Interactive state for next steps done by user
  const [completedSteps, setCompletedSteps] = useState<Record<string, boolean>>({});
  const [activeTab, setActiveTab] = useState<string>("all");

  const toggleDoc = (name: string) => {
    setCheckedDocs((prev) => ({ ...prev, [name]: !prev[name] }));
  };

  const toggleStep = (id: string) => {
    setCompletedSteps((prev) => {
      const updated = { ...prev, [id]: !prev[id] };
      const totalSteps = analysis.nextSteps.length;
      const completedCount = Object.values(updated).filter(Boolean).length;
      if (completedCount === totalSteps) {
        // Trigger celebratory confetti!
        try {
          confetti({
            particleCount: 80,
            spread: 70,
            origin: { y: 0.6 },
          });
        } catch {
          // ignore if canvas-confetti is not loaded
        }
      }
      return updated;
    });
  };

  const completedStepsCount = Object.values(completedSteps).filter(Boolean).length;

  // WhatsApp share generator
  const handleShareWhatsApp = () => {
    const text = encodeURIComponent(
      `📄 *${analysis.title}* (DocSaathi AI Summary):\n\n${analysis.simpleSummary.map((s) => `• ${s}`).join("\n")}\n\n⚠️ *Key Date:* ${analysis.importantDates[1]?.title || "Important"} - ${analysis.importantDates[1]?.date || "Check portal"}\n\n🔗 Source: ${analysis.portalUrl || "DocSaathi AI"}`
    );
    window.open(`https://api.whatsapp.com/send?text=${text}`, "_blank");
  };

  // Download summary as text file
  const handleDownloadSummary = () => {
    const content = `# ${analysis.title}
Generated by DocSaathi AI
Category: ${analysis.category.toUpperCase()} | Language: ${analysis.language.toUpperCase()}
Official Source: ${analysis.officialSource || "N/A"}
Official Portal: ${analysis.portalUrl || "N/A"}

---
## Simple Summary (Aasaan Bhasha Mein)
${analysis.simpleSummary.map((s) => `- ${s}`).join("\n")}

Key Highlight:
${analysis.keyHighlight}

---
## Important Dates & Deadlines
${analysis.importantDates.map((d) => `- ${d.title}: ${d.date} (${d.daysLeft ? `${d.daysLeft} days remaining` : d.status})`).join("\n")}

---
## Eligibility Criteria
${analysis.eligibility.map((e) => `- ${e.field}: ${e.requirement}`).join("\n")}

---
## Fees and Financial Information
${analysis.financials.items.map((f) => `- ${f.category}: ${f.amount} (${f.details || ""})`).join("\n")}
Note: ${analysis.financials.importantNote || ""}

---
## Required Documents Checklist
${analysis.requiredDocuments.map((d) => `- [ ] ${d.name} (${d.mandatory ? "Mandatory" : "Optional"}) - ${d.notes || ""}`).join("\n")}

---
## Action Steps
${analysis.nextSteps.map((s) => `${s.step}. ${s.title}: ${s.description}`).join("\n")}

---
Disclaimer: DocSaathi AI simplifies complex documents for citizens and students. Please verify with official portals.
`;

    const blob = new Blob([content], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${analysis.title.replace(/[^a-zA-Z0-9]/g, "_")}_DocSaathi_Summary.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  const makeGoogleCalendarLink = (title: string, dateStr: string) => {
    const text = encodeURIComponent(`Deadline: ${title} (${analysis.title})`);
    const details = encodeURIComponent(`Important deadline extracted by DocSaathi AI for ${analysis.title}`);
    return `https://calendar.google.com/calendar/render?action=TEMPLATE&text=${text}&details=${details}`;
  };

  return (
    <div id="results-section" className="py-10 bg-slate-50/60 border-t border-slate-200 scroll-mt-20">
      <div className="max-w-5xl mx-auto px-4 sm:px-6 lg:px-8 space-y-8">
        {/* ── Trust & Safety Disclaimer (prominent, top of results) ── */}
        <div className="flex items-start space-x-3 p-4 rounded-2xl bg-blue-50 border border-blue-200/80 text-blue-900">
          <ShieldAlert className="w-5 h-5 text-blue-600 shrink-0 mt-0.5" />
          <div className="text-xs sm:text-sm">
            <span className="font-bold text-blue-800 block mb-0.5">
              {uiLang === "hi" ? "⚠️ महत्वपूर्ण सूचना — कृपया पढ़ें" : "⚠️ Important Notice — Please Read"}
            </span>
            {uiLang === "hi"
              ? "यह DocSaathi AI द्वारा बनाया गया सारांश है। तारीखें, फ़ीस, पात्रता मानदंड और अन्य महत्वपूर्ण जानकारी को आधिकारिक दस्तावेज़ या सरकारी पोर्टल से अवश्य सत्यापित करें। DocSaathi AI किसी भी सरकारी संस्था से संबद्ध नहीं है।"
              : "This is an AI-generated summary by DocSaathi AI. Always verify all dates, fees, eligibility criteria, and requirements against the original official document or government portal before taking any action. DocSaathi AI is not affiliated with any government body."}
          </div>
        </div>

        {/* Results Banner / Header Card */}
        <div className="bg-white rounded-3xl border border-slate-200/90 shadow-card p-6 sm:p-8">
          <div className="flex flex-col md:flex-row md:items-start justify-between gap-4 pb-6 border-b border-slate-100">
            <div className="space-y-2">
              <div className="flex flex-wrap items-center gap-2">
                <span className="inline-flex items-center px-3 py-1 rounded-full text-xs font-bold bg-indigo-50 text-indigo-700 border border-indigo-200/60 uppercase tracking-wide">
                  {analysis.category}
                </span>
                <span className="inline-flex items-center px-2.5 py-1 rounded-full text-xs font-semibold bg-violet-50 text-violet-700 border border-violet-200/60">
                  {analysis.language.toUpperCase()}
                </span>
                {analysis.isDemo ? (
                  <span className="inline-flex items-center px-2.5 py-1 rounded-full text-xs font-semibold bg-amber-50 text-amber-800 border border-amber-200">
                    <Sparkles className="w-3.5 h-3.5 mr-1 text-amber-600" />
                    {t.badgeDemo}
                  </span>
                ) : (
                  <span className="inline-flex items-center px-2.5 py-1 rounded-full text-xs font-semibold bg-emerald-50 text-emerald-800 border border-emerald-200">
                    <CheckCircle2 className="w-3.5 h-3.5 mr-1 text-emerald-600" />
                    {t.badgeLive}
                  </span>
                )}
              </div>

              <h1 className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight font-display">
                {analysis.title}
              </h1>

              <p className="text-sm sm:text-base text-slate-600 font-medium">
                {analysis.tagline}
              </p>

              {analysis.officialSource && (
                <div className="flex items-center space-x-2 text-xs text-slate-500 pt-1">
                  <span className="font-semibold text-slate-700">
                    {uiLang === "hi" ? "आधिकारिक स्रोत:" : "Official Source:"}
                  </span>
                  <span>{analysis.officialSource}</span>
                  {analysis.portalUrl && (
                    <a
                      href={analysis.portalUrl}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="inline-flex items-center text-indigo-600 hover:text-indigo-800 font-semibold underline underline-offset-2 ml-1"
                    >
                      Visit Portal <ExternalLink className="w-3 h-3 ml-1" />
                    </a>
                  )}
                </div>
              )}
            </div>

            {/* Top Action Buttons */}
            <div className="flex flex-wrap items-center gap-2 shrink-0">
              <button
                type="button"
                onClick={handleShareWhatsApp}
                className="inline-flex items-center px-3.5 py-2 rounded-xl text-xs sm:text-sm font-semibold bg-emerald-600 hover:bg-emerald-700 text-white shadow-sm transition-all"
                title={t.shareWhatsApp}
              >
                <Share2 className="w-4 h-4 mr-1.5" />
                <span className="hidden sm:inline">{t.shareWhatsApp}</span>
                <span className="sm:hidden">Share</span>
              </button>

              <button
                type="button"
                onClick={handleDownloadSummary}
                className="inline-flex items-center px-3.5 py-2 rounded-xl text-xs sm:text-sm font-semibold bg-slate-100 hover:bg-slate-200 text-slate-700 border border-slate-300 shadow-xs transition-all"
                title={t.downloadSummary}
              >
                <Download className="w-4 h-4 mr-1.5 text-slate-600" />
                <span className="hidden sm:inline">{t.downloadSummary}</span>
                <span className="sm:hidden">Download</span>
              </button>

              <button
                type="button"
                onClick={handlePrint}
                className="p-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-600 border border-slate-300 transition-all hidden sm:inline-flex"
                title="Print Summary"
              >
                <Printer className="w-4 h-4" />
              </button>

              <button
                type="button"
                onClick={onReset}
                className="p-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-600 border border-slate-300 transition-all"
                title="Upload Another Document"
              >
                <RotateCcw className="w-4 h-4" />
              </button>
            </div>
          </div>

          {/* Key Highlight Banner */}
          <div className="mt-5 p-4 rounded-2xl bg-amber-50/90 border border-amber-200/90 flex items-start space-x-3 text-amber-950">
            <AlertTriangle className="w-5 h-5 text-amber-600 shrink-0 mt-0.5" />
            <div>
              <span className="text-xs font-bold uppercase tracking-wider text-amber-800 block">
                {uiLang === "hi" ? "विशेष ध्यान दें (Key Highlight):" : "Crucial Takeaway:"}
              </span>
              <p className="text-sm font-semibold mt-0.5">{analysis.keyHighlight}</p>
            </div>
          </div>

          {/* Audio Player Briefing */}
          <div className="mt-6">
            <AudioPlayer
              textToSpeak={analysis.audioScript}
              language={analysis.language}
              uiLang={uiLang}
            />
          </div>
        </div>

        {/* Section 1: Simple Summary (Aasaan Bhasha Mein) */}
        <div className="bg-white rounded-3xl border border-slate-200/90 shadow-card p-6 sm:p-7 space-y-4">
          <div className="flex items-center space-x-3 pb-3 border-b border-slate-100">
            <div className="w-10 h-10 rounded-xl bg-blue-50 text-blue-600 flex items-center justify-center">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-slate-900">{t.summaryTitle}</h3>
              <p className="text-xs text-slate-500">
                {uiLang === "hi"
                  ? "सरकारी व कानूनी भाषा को हटाकर केवल मुख्य बातें समझें।"
                  : "Every complex legal clause simplified into clear points."}
              </p>
            </div>
          </div>

          <div className="space-y-3 pt-1">
            {analysis.simpleSummary.map((point, index) => (
              <div
                key={index}
                className="flex items-start space-x-3 p-3.5 rounded-2xl bg-slate-50/80 border border-slate-100 hover:bg-indigo-50/30 transition-colors"
              >
                <div className="w-6 h-6 rounded-full bg-indigo-100 text-indigo-700 flex items-center justify-center font-bold text-xs shrink-0 mt-0.5">
                  {index + 1}
                </div>
                <p className="text-sm sm:text-base text-slate-800 font-medium leading-relaxed">
                  {point}
                </p>
              </div>
            ))}
          </div>
        </div>

        {/* Section 2: Important Dates and Deadlines */}
        <div className="bg-white rounded-3xl border border-slate-200/90 shadow-card p-6 sm:p-7 space-y-5">
          <div className="flex items-center justify-between pb-3 border-b border-slate-100">
            <div className="flex items-center space-x-3">
              <div className="w-10 h-10 rounded-xl bg-rose-50 text-rose-600 flex items-center justify-center">
                <Calendar className="w-5 h-5" />
              </div>
              <div>
                <h3 className="text-lg font-bold text-slate-900">{t.datesTitle}</h3>
                <p className="text-xs text-slate-500">
                  {uiLang === "hi" ? "अंतिम तिथि छूटने से पहले समय पर आवेदन करें।" : "Never miss a cut-off date."}
                </p>
              </div>
            </div>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3.5">
            {analysis.importantDates.map((item, index) => {
              const isUrgent = item.status === "urgent";
              return (
                <div
                  key={index}
                  className={`p-4 rounded-2xl border transition-all ${
                    isUrgent
                      ? "border-rose-300 bg-rose-50/60 shadow-xs ring-1 ring-rose-200"
                      : "border-slate-200 bg-white hover:border-indigo-300"
                  }`}
                >
                  <div className="flex items-center justify-between mb-2">
                    <span
                      className={`px-2 py-0.5 rounded-md text-[10px] font-bold uppercase tracking-wider ${
                        isUrgent
                          ? "bg-rose-100 text-rose-800"
                          : item.status === "active"
                          ? "bg-emerald-100 text-emerald-800"
                          : "bg-slate-100 text-slate-700"
                      }`}
                    >
                      {item.badge || item.status}
                    </span>

                    {item.daysLeft !== undefined && (
                      <span className="flex items-center text-[11px] font-semibold text-slate-600">
                        <Clock className="w-3 h-3 mr-1 text-slate-400" />
                        {item.daysLeft} {t.daysLeft}
                      </span>
                    )}
                  </div>

                  <h4 className="text-xs font-medium text-slate-600 line-clamp-2">
                    {item.title}
                  </h4>

                  <p className="text-base font-bold text-slate-950 mt-1">
                    {item.date}
                  </p>

                  <a
                    href={makeGoogleCalendarLink(item.title, item.date)}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="inline-flex items-center text-[11px] font-semibold text-indigo-600 hover:text-indigo-800 mt-2.5"
                  >
                    + Add to Calendar
                  </a>
                </div>
              );
            })}
          </div>
        </div>

        {/* Section 3: Eligibility & Requirements */}
        <div className="bg-white rounded-3xl border border-slate-200/90 shadow-card p-6 sm:p-7 space-y-4">
          <div className="flex items-center space-x-3 pb-3 border-b border-slate-100">
            <div className="w-10 h-10 rounded-xl bg-emerald-50 text-emerald-600 flex items-center justify-center">
              <UserCheck className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-slate-900">{t.eligibilityTitle}</h3>
              <p className="text-xs text-slate-500">
                {uiLang === "hi" ? "जांचें कि क्या आप इन शर्तों को पूरा करते हैं।" : "Verify if you satisfy these prerequisites."}
              </p>
            </div>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-3.5 pt-1">
            {analysis.eligibility.map((crit, index) => (
              <div
                key={index}
                className="p-4 rounded-2xl border border-slate-200 bg-slate-50/50 hover:bg-white hover:border-emerald-300 transition-all flex flex-col justify-between"
              >
                <div>
                  <div className="flex items-center justify-between mb-1.5">
                    <span className="text-xs font-bold uppercase tracking-wider text-slate-500">
                      {crit.field}
                    </span>
                    {crit.highlight && (
                      <span className="px-2 py-0.5 rounded-full text-[11px] font-semibold bg-emerald-100 text-emerald-800">
                        {crit.highlight}
                      </span>
                    )}
                  </div>
                  <p className="text-sm text-slate-800 font-medium leading-relaxed">
                    {crit.requirement}
                  </p>
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Section 4: Fees and Financial Information */}
        <div className="bg-white rounded-3xl border border-slate-200/90 shadow-card p-6 sm:p-7 space-y-4">
          <div className="flex items-center space-x-3 pb-3 border-b border-slate-100">
            <div className="w-10 h-10 rounded-xl bg-amber-50 text-amber-600 flex items-center justify-center">
              <CreditCard className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-slate-900">{t.feesTitle}</h3>
              <p className="text-xs text-slate-500">
                {analysis.financials.overview}
              </p>
            </div>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-3 gap-3.5">
            {analysis.financials.items.map((fee, index) => (
              <div
                key={index}
                className="p-4 rounded-2xl border border-slate-200 bg-slate-50/60 hover:bg-white transition-all"
              >
                <p className="text-xs font-medium text-slate-600">{fee.category}</p>
                <p className="text-xl font-extrabold text-slate-900 mt-1">{fee.amount}</p>
                {fee.details && (
                  <p className="text-xs text-slate-500 mt-1.5">{fee.details}</p>
                )}
              </div>
            ))}
          </div>

          {analysis.financials.importantNote && (
            <div className="p-3.5 rounded-xl bg-blue-50 border border-blue-200/80 text-blue-900 text-xs sm:text-sm flex items-start space-x-2.5">
              <Info className="w-4 h-4 text-blue-600 shrink-0 mt-0.5" />
              <span>{analysis.financials.importantNote}</span>
            </div>
          )}
        </div>

        {/* Section 5: Required Documents Checklist */}
        <div className="bg-white rounded-3xl border border-slate-200/90 shadow-card p-6 sm:p-7 space-y-4">
          <div className="flex items-center justify-between pb-3 border-b border-slate-100">
            <div className="flex items-center space-x-3">
              <div className="w-10 h-10 rounded-xl bg-purple-50 text-purple-600 flex items-center justify-center">
                <FolderCheck className="w-5 h-5" />
              </div>
              <div>
                <h3 className="text-lg font-bold text-slate-900">{t.docsTitle}</h3>
                <p className="text-xs text-slate-500">
                  {uiLang === "hi"
                    ? "टिक करें जो दस्तावेज़ आपके पास तैयार हैं:"
                    : "Check off items you have already arranged:"}
                </p>
              </div>
            </div>

            <span className="text-xs font-semibold px-2.5 py-1 rounded-full bg-purple-50 text-purple-700">
              {Object.values(checkedDocs).filter(Boolean).length} / {analysis.requiredDocuments.length} Ready
            </span>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
            {analysis.requiredDocuments.map((doc, index) => {
              const isChecked = checkedDocs[doc.name] || false;
              return (
                <div
                  key={index}
                  onClick={() => toggleDoc(doc.name)}
                  className={`cursor-pointer p-3.5 rounded-2xl border transition-all flex items-start space-x-3 ${
                    isChecked
                      ? "border-emerald-300 bg-emerald-50/50 shadow-xs"
                      : "border-slate-200 bg-white hover:bg-slate-50"
                  }`}
                >
                  <input
                    type="checkbox"
                    checked={isChecked}
                    onChange={() => {}}
                    className="mt-1 h-4 w-4 rounded border-slate-300 text-emerald-600 focus:ring-emerald-500 cursor-pointer"
                  />
                  <div className="min-w-0 flex-1">
                    <div className="flex items-center space-x-2">
                      <span className={`text-sm font-semibold ${isChecked ? "line-through text-slate-500" : "text-slate-900"}`}>
                        {doc.name}
                      </span>
                      <span
                        className={`text-[10px] font-bold px-1.5 py-0.5 rounded ${
                          doc.mandatory
                            ? "bg-rose-100 text-rose-800"
                            : "bg-slate-100 text-slate-600"
                        }`}
                      >
                        {doc.mandatory ? "Mandatory" : "Optional"}
                      </span>
                    </div>
                    {doc.notes && (
                      <p className="text-xs text-slate-500 mt-1">{doc.notes}</p>
                    )}
                  </div>
                </div>
              );
            })}
          </div>
        </div>

        {/* Section 6: Next Steps Checklist (Interactive) */}
        <div className="bg-white rounded-3xl border border-slate-200/90 shadow-card p-6 sm:p-7 space-y-5">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between pb-3 border-b border-slate-100 gap-2">
            <div className="flex items-center space-x-3">
              <div className="w-10 h-10 rounded-xl bg-indigo-50 text-indigo-600 flex items-center justify-center">
                <CheckSquare className="w-5 h-5" />
              </div>
              <div>
                <h3 className="text-lg font-bold text-slate-900">{t.stepsTitle}</h3>
                <p className="text-xs text-slate-500">
                  {uiLang === "hi"
                    ? "इन चरणों का क्रमवार पालन करें और चेकबॉक्स पर टिक करते जाएं।"
                    : "Follow these exact sequential actions. Tick off as you complete them."}
                </p>
              </div>
            </div>

            {/* Progress indicator */}
            <div className="flex items-center space-x-2 bg-indigo-50 px-3 py-1.5 rounded-xl border border-indigo-100">
              <span className="text-xs font-bold text-indigo-900">
                {completedStepsCount} / {analysis.nextSteps.length} {t.stepsProgress}
              </span>
            </div>
          </div>

          <div className="space-y-3">
            {analysis.nextSteps.map((step) => {
              const isDone = completedSteps[step.id] || false;
              return (
                <div
                  key={step.id}
                  onClick={() => toggleStep(step.id)}
                  className={`cursor-pointer p-4 rounded-2xl border transition-all flex items-start space-x-3.5 ${
                    isDone
                      ? "border-emerald-300 bg-emerald-50/40"
                      : "border-slate-200 bg-white hover:border-indigo-300 hover:bg-slate-50/60"
                  }`}
                >
                  <div
                    className={`w-7 h-7 rounded-full flex items-center justify-center text-xs font-bold shrink-0 mt-0.5 transition-colors ${
                      isDone
                        ? "bg-emerald-600 text-white"
                        : "bg-indigo-100 text-indigo-800"
                    }`}
                  >
                    {isDone ? "✓" : step.step}
                  </div>

                  <div className="flex-1 min-w-0">
                    <h4 className={`text-sm font-bold ${isDone ? "line-through text-slate-500" : "text-slate-900"}`}>
                      {step.title}
                    </h4>
                    <p className="text-xs sm:text-sm text-slate-600 mt-0.5 leading-relaxed">
                      {step.description}
                    </p>
                  </div>
                </div>
              );
            })}
          </div>

          {/* Official Portal Action CTA */}
          {analysis.portalUrl && (
            <div className="pt-2 text-center">
              <a
                href={analysis.portalUrl}
                target="_blank"
                rel="noopener noreferrer"
                className="inline-flex items-center px-6 py-3 rounded-2xl bg-indigo-600 hover:bg-indigo-700 text-white font-bold text-sm shadow-md shadow-indigo-600/25 transition-all hover:scale-105 active:scale-95"
              >
                <span>{uiLang === "hi" ? "आधिकारिक पोर्टल पर जाएं" : "Go to Official Portal"}</span>
                <ExternalLink className="w-4 h-4 ml-2" />
              </a>
            </div>
          )}
        </div>

        {/* Section 6.5: Unclear, Missing or Ambiguous Information */}
        {analysis.unclearOrMissingInfo && analysis.unclearOrMissingInfo.length > 0 && (
          <div className="bg-white rounded-3xl border border-amber-200/90 shadow-card p-6 sm:p-7 space-y-4">
            <div className="flex items-center space-x-3 pb-3 border-b border-amber-100">
              <div className="w-10 h-10 rounded-xl bg-amber-50 text-amber-600 flex items-center justify-center">
                <AlertTriangle className="w-5 h-5" />
              </div>
              <div>
                <h3 className="text-lg font-bold text-slate-900">
                  {uiLang === "hi"
                    ? "दस्तावेज़ में अस्पष्ट या छूटी हुई जानकारी"
                    : "Unclear, Missing or Ambiguous Information"}
                </h3>
                <p className="text-xs text-slate-500">
                  {uiLang === "hi"
                    ? "यह विवरण इस दस्तावेज़ में स्पष्ट रूप से मौजूद नहीं है, आधिकारिक कार्यालय से पुष्टि करें।"
                    : "These details are omitted or ambiguous in this document; verify with the issuing authority."}
                </p>
              </div>
            </div>

            <div className="space-y-2.5">
              {analysis.unclearOrMissingInfo.map((item, idx) => (
                <div
                  key={idx}
                  className="flex items-start space-x-3 p-3.5 rounded-2xl bg-amber-50/50 border border-amber-200/60 text-xs sm:text-sm text-amber-950 font-medium"
                >
                  <span className="w-5 h-5 rounded-full bg-amber-200/80 text-amber-800 flex items-center justify-center text-xs font-bold shrink-0 mt-0.5">
                    ?
                  </span>
                  <p className="leading-relaxed">{item}</p>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Section 7: Ask Questions About This Document (Interactive Q&A) */}
        <DocumentQnA analysis={analysis} uiLang={uiLang} apiKey={apiKey} />

        {/* Warning Disclaimers */}
        {analysis.warnings && analysis.warnings.length > 0 && (
          <div className="p-4 rounded-2xl bg-rose-50/70 border border-rose-200 text-rose-900 text-xs space-y-1">
            <div className="flex items-center space-x-1.5 font-bold uppercase tracking-wider text-rose-800">
              <ShieldAlert className="w-4 h-4 text-rose-600" />
              <span>{uiLang === "hi" ? "सावधानी / महत्वपूर्ण चेतावनी:" : "Crucial Safety Advisory:"}</span>
            </div>
            {analysis.warnings.map((w, i) => (
              <p key={i} className="pl-5">• {w}</p>
            ))}
          </div>
        )}
      </div>
    </div>
  );
};
